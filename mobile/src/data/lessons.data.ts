// Helper function to get a lesson by ID
export const getLessonById = (lessonId: string): Lesson | undefined => {
  return LESSONS_DATA[lessonId];
};

// Helper function to get an activity by ID
export const getActivityById = (lessonId: string, activityId: string) => {
  const lesson = LESSONS_DATA[lessonId];
  if (!lesson) return undefined;
  return lesson.activities.find((a) => a.id === activityId);
};
